"""chrome_cookies.py —— 尽最大努力从本机 Chrome 取出 B 站登录 cookie，写成 Netscape cookies 文件。

背景（Chrome 127+）：
  - cookie 数据库被 App-Bound Encryption（ABE）保护；普通进程读取会报 requires admin。
  - 浏览器运行时 `Network/Cookies` 被独占锁住（WinError 32）。
  - `yt-dlp --cookies-from-browser chrome` 在 ABE 下会失败。

策略（按顺序尝试，任一成功即停）：
  1) yt-dlp --cookies-from-browser chrome            （最快，ABE 前版本可用）
  2) 临时目录复制 profile + 无头 Chrome + CDP 读取    （不打扰正在运行的 Chrome；新版本可能可用）
  3) 已运行 CDP 端口（配合 tools/chrome-debug.ps1 重启后的 Chrome）  --cdp 9222
  4) browser_cookie3（需要管理员 / 在 ABE 下可能失败）
用法：
  python tools/chrome_cookies.py                     # 依次尝试 1,2,4
  python tools/chrome_cookies.py --cdp 9222          # 连到已开调试端口的 Chrome
  python tools/chrome_cookies.py -o cookies/bilibili.txt --json
"""
