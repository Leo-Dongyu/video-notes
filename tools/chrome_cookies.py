def log(*a):
    print("[chrome-cookies]", *a, flush=True)


def write_netscape(cookies, out_path):
    """cookies: list of {name,value,domain,path,secure,httpOnly,expires}"""
    lines = ["# Netscape HTTP Cookie File", "# generated by video-notes tools/chrome_cookies.py", ""]
    n = 0
    for c in cookies:
        name, value, domain = c.get("name"), c.get("value"), c.get("domain", "")
        if not name or value is None or DOMAIN not in domain:
            continue
        exp = c.get("expires")
        try:
            exp = int(exp)
        except (TypeError, ValueError):
            exp = 0
        if exp < 0:
            exp = 0
        lines.append("\t".join([
            domain, "TRUE" if domain.startswith(".") else "FALSE",
            c.get("path") or "/", "TRUE" if c.get("secure") else "FALSE",
            str(exp), name, str(value),
        ]))
        n += 1
    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return n


