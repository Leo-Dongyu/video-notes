def find_chrome():
    for c in CHROME_CANDIDATES:
        if Path(c).exists():
            return c
    return None


class WS:
    """最小 WebSocket 客户端（只用于本地 CDP）。"""

    def __init__(self, url):
        # ws://127.0.0.1:9333/devtools/page/XXX
        assert url.startswith("ws://"), url
        rest = url[5:]
        hostport, path = rest.split("/", 1)
        path = "/" + path
        host, port = hostport.split(":")
        self.sock = socket.create_connection((host, int(port)), timeout=20)
        key = base64.b64encode(os.urandom(16)).decode()
        req = (("GET %s HTTP/1.1\r\nHost: %s\r\nUpgrade: websocket\r\nConnection: Upgrade\r\n"
                "Sec-WebSocket-Key: %s\r\nSec-WebSocket-Version: 13\r\n\r\n") % (path, hostport, key))
        self.sock.sendall(req.encode())
        buf = b""
        while b"\r\n\r\n" not in buf:
            buf += self.sock.recv(4096)
        head = buf.split(b"\r\n\r\n", 1)[0].decode("latin-1")
        if " 101 " not in head.split("\r\n")[0]:
            raise RuntimeError("WebSocket 握手失败：" + head.split("\r\n")[0])

    def send(self, text):
        data = text.encode()
        mask = os.urandom(4)
        header = bytearray([0x81])
        n = len(data)
        if n < 126:
            header.append(0x80 | n)
        elif n < 65536:
            header.append(0x80 | 126)
            header += n.to_bytes(2, "big")
        else:
            header.append(0x80 | 127)
            header += n.to_bytes(8, "big")
        masked = bytes(b ^ mask[i % 4] for i, b in enumerate(data))
        self.sock.sendall(bytes(header) + mask + masked)

    def _read_exact(self, n):
        buf = b""
        while len(buf) < n:
            chunk = self.sock.recv(n - len(buf))
            if not chunk:
                raise RuntimeError("连接关闭")
            buf += chunk
        return buf

    def recv(self):
        while True:
            b1, b2 = self._read_exact(2)
            opcode = b1 & 0x0F
            masked = b2 & 0x80
            ln = b2 & 0x7F
            if ln == 126:
                ln = int.from_bytes(self._read_exact(2), "big")
            elif ln == 127:
                ln = int.from_bytes(self._read_exact(8), "big")
            mask = self._read_exact(4) if masked else b""
            data = self._read_exact(ln)
            if masked:
                data = bytes(b ^ mask[i % 4] for i, b in enumerate(data))
            if opcode == 1:
                return data.decode("utf-8", "replace")
            if opcode == 8:
                raise RuntimeError("WebSocket 已关闭")
            if opcode == 9:  # ping
                self.sock.sendall(bytes([0x8A, 0x80]) + os.urandom(4))
            # 其它帧忽略

    def close(self):
        try:
            self.sock.close()
        except Exception:
            pass


def cdp_get_cookies(port, timeout=25):
    base = "http://127.0.0.1:%d" % port
    deadline = time.time() + timeout
    info = None
    while time.time() < deadline:
        try:
            with urllib.request.urlopen(base + "/json/version", timeout=2) as r:
                info = json.loads(r.read().decode())
            break
        except Exception:
            time.sleep(0.5)
    if not info:
        raise RuntimeError("CDP 端口未就绪")
    browser_ws = info.get("webSocketDebuggerUrl")
    if not browser_ws:
        raise RuntimeError("拿不到 CDP WebSocket 地址")
    ws = WS(browser_ws)
    try:
        msg = {"id": 1, "method": "Network.getAllCookies", "params": {}}
        ws.send(json.dumps(msg))
        while True:
            data = ws.recv()
            try:
                payload = json.loads(data)
            except Exception:
                continue
            if payload.get("id") == 1:
                cookies = (payload.get("result") or {}).get("cookies") or []
                return cookies
    finally:
        ws.close()


def try_temp_profile_cdp(out):
    chrome = find_chrome()
    if not chrome:
        return None, "找不到 chrome.exe"
    if not (USER_DATA / "Default" / "Network" / "Cookies").exists():
        return None, "找不到 Chrome Cookies 数据库"
    tmpdir = Path(tempfile.mkdtemp(prefix="vn-chrome-"))
    try:
        dst = tmpdir / "User Data"
        (dst / "Default" / "Network").mkdir(parents=True, exist_ok=True)
        shutil.copy2(USER_DATA / "Local State", dst / "Local State")
        for name in ("Cookies", "Cookies-journal"):
            src = USER_DATA / "Default" / "Network" / name
            if src.exists():
                shutil.copy2(src, dst / "Default" / "Network" / name)
        port = 9333
        cmd = [chrome, "--headless=new", "--remote-debugging-port=%d" % port,
               "--remote-allow-origins=*", "--user-data-dir=%s" % dst,
               "--no-first-run", "--no-default-browser-check", "about:blank"]
        proc = subprocess.Popen(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        try:
            cookies = cdp_get_cookies(port)
        finally:
            proc.terminate()
            try:
                proc.wait(timeout=10)
            except Exception:
                proc.kill()
        n = write_netscape(cookies, out)
        if n:
            return n, "Chrome 临时 profile + CDP（headless）"
        return None, "CDP 读到 cookie 但无 bilibili 登录态（profile 未登录？）"
    except Exception as e:  # noqa: BLE001
        return None, "临时 profile CDP 失败：%s" % (str(e)[:200])
    finally:
        shutil.rmtree(tmpdir, ignore_errors=True)


# ------------------------------------------------------------------ 3) 已开 CDP 端口

def try_cdp_port(port, out):
    try:
        cookies = cdp_get_cookies(port)
        n = write_netscape(cookies, out)
        if n:
            return n, "运行中 Chrome 的 CDP 端口 %d" % port
        return None, "CDP 端口 %d 无 bilibili 登录态" % port
    except Exception as e:  # noqa: BLE001
        return None, "CDP 端口 %d 失败：%s" % (port, str(e)[:160])


# ------------------------------------------------------------------ 4) browser_cookie3

def try_browser_cookie3(out):
    try:
        import browser_cookie3  # type: ignore
    except Exception:
        return None, "browser_cookie3 未安装"
    try:
        jar = browser_cookie3.chrome(domain_name=DOMAIN)
        cookies = [{"name": c.name, "value": c.value, "domain": c.domain or "." + DOMAIN,
                    "path": c.path, "secure": c.secure, "expires": c.expires or 0} for c in jar]
        n = write_netscape(cookies, out)
        if n:
            return n, "browser_cookie3（需管理员）"
        return None, "browser_cookie3 未读到 bilibili cookie"
    except Exception as e:  # noqa: BLE001
        return None, "browser_cookie3 失败：%s" % (str(e)[:160])


# ------------------------------------------------------------------ main

def existing_ok(out):
    p = Path(out)
    if not p.exists():
        return False
    txt = p.read_text(encoding="utf-8", errors="replace")
    return ("SESSDATA" in txt) and ("bilibili" in txt.lower())


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", "--out", default=str(ROOT / "cookies" / "bilibili.txt"))
    ap.add_argument("--cdp", type=int, default=None, help="连接已在运行的 Chrome 调试端口")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()
    results = []
    attempts = []
    if not args.force and existing_ok(args.out):
        results.append({"method": "existing", "ok": True, "count": count_cookies(args.out),
                        "detail": "已有可用 cookies 文件"})
    else:
        if args.cdp:
            attempts.append(("cdp", lambda: try_cdp_port(args.cdp, args.out)))
        else:
            attempts.append(("ytdlp", lambda: try_ytdlp(args.out)))
            attempts.append(("temp-profile-cdp", lambda: try_temp_profile_cdp(args.out)))
            attempts.append(("browser-cookie3", lambda: try_browser_cookie3(args.out)))
        for name, fn in attempts:
            log("尝试：", name)
            n, detail = fn()
            results.append({"method": name, "ok": bool(n), "count": n or 0, "detail": detail})
            if n:
                break
    ok = any(r["ok"] for r in results)
    if args.json:
        print(json.dumps({"ok": ok, "out": args.out, "results": results}, ensure_ascii=False))
    else:
        for r in results:
            log(("成功" if r["ok"] else "失败"), r["method"], "-", r["detail"])
        log("结果：", "已写入 " + args.out if ok else "全部失败")
    sys.exit(0 if ok else 2)


def count_cookies(path):
    try:
        txt = Path(path).read_text(encoding="utf-8", errors="replace")
        return sum(1 for l in txt.splitlines() if l and not l.startswith("#"))
    except Exception:
        return 0


if __name__ == "__main__":
    main()
