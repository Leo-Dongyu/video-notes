def try_ytdlp(out):
    yt = None
    for c in ("yt-dlp", str(Path(sys.executable).parent / "Scripts" / "yt-dlp.exe"),
              str(Path(sys.executable).parent / "Scripts" / "yt-dlp")):
        try:
            p = subprocess.run([c, "--version"], capture_output=True, text=True, timeout=15)
            if p.returncode == 0:
                yt = c
                break
        except Exception:
            continue
    if not yt:
        return None, "yt-dlp 不存在"
    tmp = Path(tempfile.gettempdir()) / "vn-yt-cookies.txt"
    cmd = [yt, "--cookies-from-browser", "chrome", "--cookies", str(tmp),
           "--simulate", "--skip-download", "--no-warnings", "https://www.bilibili.com/"]
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, timeout=120)
        err = (p.stderr or "").strip()
        if tmp.exists() and tmp.stat().st_size > 0:
            txt = tmp.read_text(encoding="utf-8", errors="replace")
            if "bilibili" in txt.lower():
                n = write_netscape(parse_netscape(txt), out)
                if n:
                    return n, "yt-dlp --cookies-from-browser chrome"
        return None, ("yt-dlp 失败：" + (err.splitlines()[0] if err else "未知"))
    except Exception as e:  # noqa: BLE001
        return None, "yt-dlp 异常：%s" % (str(e)[:200])


def parse_netscape(txt):
    out = []
    for line in txt.splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        f = line.split("\t")
        if len(f) < 7:
            continue
        out.append({"domain": f[0], "path": f[2], "secure": f[3].upper() == "TRUE",
                    "expires": f[4], "name": f[5], "value": f[6]})
    return out


